/** Localize user-facing errors while keeping core/service exceptions stable for callers. */
export function messageText(message: string, language: string): string {
  if (language !== 'ru') return message;
  if (russianErrors[message]) return russianErrors[message];
  if (message.includes('\n'))
    return message
      .split('\n')
      .map((line) => messageText(line, language))
      .join('\n');
  const patterns: [RegExp, (m: RegExpMatchArray) => string][] = [
    [/^Invalid date\. (.+)$/, (m) => `Некорректная дата. Формат: ${m[1]}`],
    [
      /^(COUNT|INTERVAL) must be a positive integer no greater than 100000\.$/,
      (m) => `${m[1]} должен быть целым числом от 1 до 100 000.`,
    ],
    [/^Invalid (BY\w+) value\.$/, (m) => `Некорректное значение ${m[1]} в правиле повтора.`],
    [/^Note not found: (.+)$/, (m) => `Заметка не найдена: ${m[1]}`],
    [
      /^A file blocks the planner folder: (.+)$/,
      (m) => `Файл мешает созданию папки планировщика: ${m[1]}`,
    ],
    [
      /^Unsupported future planner schema: (.+)$/,
      (m) => `Более новая версия схемы планировщика: ${m[1]}`,
    ],
    [
      /^Invalid planner metadata: (.+)$/,
      (m) => `Некорректные свойства заметки планировщика: ${m[1]!.split(': ')[0]}`,
    ],
    [
      /^Unresolved project: (.+) → (.+)\. Assigned to inbox\.$/,
      (m) => `Проект не найден: ${m[1]} → ${m[2]}. Задача помещена во входящие.`,
    ],
    [
      /^Multiple projects: (.+)\. The first is active; all original links are retained in topLegacyProjects\.$/,
      (m) =>
        `Несколько проектов: ${m[1]}. Выбран первый; все исходные ссылки сохранены в topLegacyProjects.`,
    ],
    [
      /^Missing repeat start: (.+)\. Used (.+)\.$/,
      (m) => `Не указано начало повторов: ${m[1]}. Использована дата ${m[2]}.`,
    ],
    [
      /^Check recurrence in (.+): (.+)$/,
      (m) => `Проверьте повтор в ${m[1]}: ${messageText(m[2]!, language)}`,
    ],
    [
      /^Unfinished timer in (.+)\. Original entry retained; no duration invented\.$/,
      (m) =>
        `Незавершённый таймер в ${m[1]}. Исходная запись сохранена; длительность не рассчитана.`,
    ],
  ];
  for (const [pattern, render] of patterns) {
    const match = message.match(pattern);
    if (match) return render(match);
  }
  console.error('[Tiny Planner]', message);
  return 'Не удалось выполнить действие. Подробности в консоли Obsidian.';
}
